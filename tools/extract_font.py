"""Reconstruct the IE15 character ROM from the archived pixel listing.

The result must match MAME's independently recorded ROM digest exactly.
This script never draws, guesses, or substitutes any glyph.
"""
from base64 import b64encode
from hashlib import sha1, sha256
from pathlib import Path
from zipfile import ZipFile
import re
import zlib

ROOT = Path(__file__).resolve().parents[1]
ARCHIVE = ROOT / 'assets/fonts/15IE_CHR.ZIP'
EXPECTED_SHA1 = '6af9fb75f5375943d5c0ce9ed408e0fb4621b17e'
EXPECTED_CRC = 0xed16bf6b

with ZipFile(ARCHIVE) as archive:
    listing = archive.read('CHARS.TXT').decode('ascii')
rows = [line for line in listing.splitlines() if line.strip()]
if len(rows) != 256 * 8:
    raise ValueError('Expected eight rows for each of the 256 ROM slots')
data = bytearray()
for i, line in enumerate(rows):
    match = re.fullmatch(r'([0-9A-F]{2}):(\.[.*]{7}\.)', line)
    if not match or int(match[1], 16) != i // 8:
        raise ValueError('Invalid character listing at row ' + str(i))
    # The listing adds a blank left margin before the ROM's eight output bits.
    # Bits 7..1 form the seven visible columns; bit 0 is unused.
    data.append(int(''.join('1' if c == '*' else '0' for c in match[2][1:]), 2))
if sha1(data).hexdigest() != EXPECTED_SHA1 or zlib.crc32(data) != EXPECTED_CRC:
    raise ValueError('Recovered ROM does not match MAME')

(ARCHIVE.parent / 'chargen-15ie.bin').write_bytes(data)
encoded = b64encode(data).decode('ascii')
source = (
    '// Generated by tools/extract_font.py from assets/fonts/15IE_CHR.ZIP.\n'
    '// Source and verification: docs/font-15ie.md. Do not edit glyph pixels.\n'
    '// SHA-1: ' + EXPECTED_SHA1 + '\n'
    'export const IE15_ROM = Uint8Array.from(atob(\n'
    "  '" + encoded + "'\n"
    '), c => c.charCodeAt(0));\n'
)
(ROOT / 'src/font-rom.js').write_text(source)
print('Verified 2048-byte IE15 ROM; SHA-256 ' + sha256(data).hexdigest())
